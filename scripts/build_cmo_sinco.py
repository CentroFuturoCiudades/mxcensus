"""Build the CMO → SINCO bridge for CGPV 2000's occupation (maintainer-only).

Writes ``src/mxcensus/_yaml/cpv_cmo_sinco.csv``: for every code of the Clasificación
Mexicana de Ocupaciones (CMO) in INEGI's comparison table or in CGPV 2000's ``OCUACTIV_C``,
the SINCO 2011 group (two digits) ``cpv_derived`` gives it as ``OCUPACION_C_COARSE`` — the
coarse occupation every other edition 2010–2025 has. Read by ``mxcensus.cpv_derived``.

**Source.** INEGI's *Tablas comparativas* of the SINCO 2011 (update of November 2012): the
sheet ``SINCO-CMO`` lists each SINCO unit group (four digits) with the CMO codes it takes
(several rows when it takes several). INEGI's site no longer serves it; the Internet
Archive keeps the file INEGI's classifier page linked (``_URL``, checked against
``_SHA256``), cached in ``data/dict/sinco/``. CGPV 2000 codes its occupations in that CMO:
447 of its 460 codes (99.45% of the employed, weighted) are in the table.

**The bridge**, per CMO code (``RULE``):

- ``table`` — the table gives it one SINCO group;
- ``panel`` — the table splits it across groups (domestic workers 8200: 51 or 96): the
  group most of its people take among them, on ENOE's rotating panel across INEGI's switch
  from the CMO to the SINCO (the same persons coded CMO in 2012-T2, SINCO in 2012-T3;
  ``panel``, weighted by T3's ``fac``; ``SHARE`` = that group's share of the linked persons
  in the table's groups, ``PERSONS`` = them, unweighted);
- for a code the table lacks: ``panel`` again, any group, when at least ``_MIN_PERSONS``
  linked persons hold it and ``_MIN_SHARE`` of them agree; else ``siblings`` — the one group
  the table gives the codes of its CMO subgroup (its first three digits);
- ``not placed`` — none of these: group 99, «No especificado».

``GROUP`` is the SINCO 2011 group; ``cpv_derived`` folds its 59 into 52 (SINCO 2019, as for
2010 and 2015). ``UNITS`` lists the table's SINCO units for the code.

``--check`` writes ``docs/cpv/CMO_SINCO_REPORT.md``: the rules, the split and absent codes,
the bridge on ENOE 2012-T2 against 2012-T3's SINCO groups, CGPV 2000 against Censo 2010.

Usage::

    .venv/bin/python scripts/build_cmo_sinco.py              # download (once) + build
    .venv/bin/python scripts/build_cmo_sinco.py --check      # + the report (the mirror's
                                                             #   CPV 2000/2010 personas)
"""
from __future__ import annotations

import argparse
import hashlib
import sys
import urllib.request
from pathlib import Path

import pandas as pd

_REPO_ROOT = Path(__file__).resolve().parent.parent
sys.path.insert(0, str(_REPO_ROOT / "scripts"))
sys.path.insert(0, str(_REPO_ROOT / "src"))

import _dict_fd  # noqa: E402

_URL = ("http://web.archive.org/web/20140226192832id_/http://www.inegi.org.mx/est/contenidos/"
        "proyectos/aspectosmetodologicos/clasificadoresycatalogos/doc/"
        "sinco_tablas_comparativas.xls")
_SHA256 = "2fa4813f94d8437526a3b71c7b809bae5d68284700289e1eb35129e997efc5b4"
_DEFAULT_XLS = _REPO_ROOT / "data" / "dict" / "sinco" / "sinco_tablas_comparativas.xls"
_DEFAULT_OUTPUT = _REPO_ROOT / "src" / "mxcensus" / "_yaml" / "cpv_cmo_sinco.csv"
_DEFAULT_MIRROR = _REPO_ROOT / "data" / "parquet"
_DEFAULT_REPORT = _REPO_ROOT / "docs" / "cpv" / "CMO_SINCO_REPORT.md"

# the ENOE quarters either side of INEGI's switch (2012-T3: SINCO and the CMPE)
_BEFORE, _AFTER = "2012t2", "2012t3"
_KEY = ("cd_a", "ent", "con", "v_sel", "n_hog", "h_mud", "n_ren")
# a code the table lacks takes the panel's group only on this much evidence
_MIN_PERSONS, _MIN_SHARE = 10, 0.5
_NOT_PLACED = "99"

_HEADER = """\
# CMO -> SINCO 2011 group bridge for CGPV 2000's occupation (OCUACTIV_C). Generated by
# scripts/build_cmo_sinco.py from INEGI's SINCO 2011 comparison tables (SINCO-CMO, November
# 2012) and ENOE's panel across the 2012-T2/T3 switch; do not edit by hand. GROUP = the SINCO
# 2011 group (99 = not placed), RULE = table | panel | siblings | not placed, SHARE/PERSONS =
# the panel's evidence, UNITS = the table's SINCO units. Read by mxcensus.cpv_derived.
"""


def download(path: Path) -> Path:
    """Fetch the comparison workbook from the Internet Archive into ``path``."""
    path.parent.mkdir(parents=True, exist_ok=True)
    with urllib.request.urlopen(_URL, timeout=300) as r:
        body = r.read()
    if hashlib.sha256(body).hexdigest() != _SHA256:
        raise SystemExit(f"{_URL}: not the expected file (sha256 differs)")
    path.write_bytes(body)
    return path


def table_pairs(path: Path) -> pd.DataFrame:
    """The ``SINCO-CMO`` sheet as (``SINCO`` unit, ``CMO`` code, ``LABEL``) pairs: a CMO code
    beside a unit group, or on the rows after it (a unit taking several codes)."""
    if hashlib.sha256(path.read_bytes()).hexdigest() != _SHA256:
        raise SystemExit(f"{path}: not the expected file (sha256 differs); --download")
    rows = _dict_fd.read_workbook(path)["SINCO-CMO"]
    pairs, unit = [], None
    for r in rows:
        sinco, cmo = r.get("D", "").strip(), r.get("F", "").strip()
        if sinco.isdigit():
            unit = sinco if len(sinco) == 4 else None
        if len(cmo) == 4 and cmo.isdigit():
            if unit is None:
                raise SystemExit(f"{path}: CMO {cmo} beside no SINCO unit group")
            pairs.append((unit, cmo, r.get("G", "").strip()))
    return pd.DataFrame(pairs, columns=["SINCO", "CMO", "LABEL"])


def _coe1(period: str) -> pd.DataFrame:
    """ENOE's COE1 of one quarter: the person key, the visit, the occupation, the weight."""
    from mxcensus import load_enoe
    t = load_enoe(table="coe1", period=period)
    t.columns = [c.lower() for c in t.columns]
    t = t[[*_KEY, "n_ent", "p3", "fac"]].copy()
    for c in (*_KEY, "n_ent"):
        t[c] = t[c].str.strip().str.lstrip("0")
    t["p3"] = t["p3"].str.strip()
    t = t[t["p3"].fillna("") != ""]
    t["p3"] = t["p3"].str.zfill(4)
    t["fac"] = pd.to_numeric(t["fac"])
    return t


def panel(before: str = _BEFORE, after: str = _AFTER) -> pd.DataFrame:
    """The persons ENOE interviewed in ``before`` (CMO) and again the next quarter, ``after``
    (SINCO), employed both times: ``CMO``, ``SINCO``, ``W`` (``after``'s weight)."""
    a, b = _coe1(before), _coe1(after)
    a["n_ent"] = (a["n_ent"].astype(int) + 1).astype(str)
    m = a.merge(b, on=[*_KEY, "n_ent"], suffixes=("_a", "_b"))
    return pd.DataFrame({"CMO": m["p3_a"], "SINCO": m["p3_b"], "W": m["fac_b"]})


def codes_2000(mirror: Path) -> pd.Series:
    """CGPV 2000's occupation codes → their weighted employed (``FACTOR``), from the mirror."""
    import pyarrow.parquet as pq
    files = [mirror / f"cpv_personas_2000_{s:02d}.parquet" for s in range(1, 33)]
    missing = [f.name for f in files if not f.exists()]
    if missing:
        raise SystemExit(f"{mirror}: CPV 2000 personas missing ({missing[:3]}…)")
    frames = [pq.read_table(f, columns=["OCUACTIV_C", "FACTOR"]).to_pandas() for f in files]
    d = pd.concat(frames, ignore_index=True).dropna(subset=["OCUACTIV_C"])
    return d.assign(W=pd.to_numeric(d["FACTOR"])).groupby("OCUACTIV_C")["W"].sum()


def bridge(pairs: pd.DataFrame, links: pd.DataFrame, codes: pd.Index) -> pd.DataFrame:
    """One row per CMO code of the table or of ``codes`` (``CMO``, ``GROUP``, ``RULE``,
    ``SHARE``, ``PERSONS``, ``UNITS``): the rules of the module's docstring."""
    pairs = pairs.assign(GROUP=pairs["SINCO"].str[:2])
    units = pairs.groupby("CMO")["SINCO"].agg(lambda s: " ".join(dict.fromkeys(s)))
    groups = pairs.groupby("CMO")["GROUP"].agg(lambda s: sorted(set(s)))
    links = links.assign(GROUP=links["SINCO"].str[:2])
    by_code = {c: g for c, g in links.groupby("CMO")}
    placed = {c: gs[0] for c, gs in groups.items() if len(gs) == 1}

    def evidence(code: str, allowed: list[str] | None) -> tuple[str | None, float, int]:
        g = by_code.get(code)
        if g is None:
            return None, 0.0, 0
        if allowed is not None:
            g = g[g["GROUP"].isin(allowed)]
        if g.empty:
            return None, 0.0, 0
        w = g.groupby("GROUP")["W"].sum().sort_values(ascending=False, kind="stable")
        return w.index[0], float(w.iloc[0] / w.sum()), len(g)

    out = []
    for code in sorted(set(groups.index) | set(codes)):
        if code in placed:
            out.append((code, placed[code], "table", None, None))
            continue
        if code in groups.index:                       # split across groups by the table
            group, share, n = evidence(code, groups[code])
            out.append((code, group or _NOT_PLACED, "panel" if group else "not placed",
                        share if group else None, n or None))
            continue
        group, share, n = evidence(code, None)         # not in the table
        if group and n >= _MIN_PERSONS and share >= _MIN_SHARE:
            out.append((code, group, "panel", share, n))
            continue
        siblings = {g for c, gs in groups.items() if c[:3] == code[:3] for g in gs}
        if len(siblings) == 1:
            out.append((code, siblings.pop(), "siblings", None, None))
        else:
            out.append((code, _NOT_PLACED, "not placed", share or None, n or None))
    table = pd.DataFrame(out, columns=["CMO", "GROUP", "RULE", "SHARE", "PERSONS"])
    table["SHARE"] = table["SHARE"].map(lambda s: "" if pd.isna(s) else f"{s:.3f}")
    table["PERSONS"] = table["PERSONS"].map(lambda n: "" if pd.isna(n) else str(int(n)))
    table["UNITS"] = table["CMO"].map(units).fillna("")
    return table


def write(table: pd.DataFrame, path: Path) -> None:
    """The bundled CSV with its commented header (reproducible bytes)."""
    path.write_text(_HEADER + table.to_csv(index=False, lineterminator="\n"), encoding="utf-8")


# --------------------------------------------------------------------------- check

def _md(df: pd.DataFrame, index: bool = False) -> str:
    if index:
        df = df.reset_index()
    cols = [str(c) for c in df.columns]
    lines = ["| " + " | ".join(cols) + " |", "|" + "---|" * len(cols)]
    for row in df.itertuples(index=False):
        lines.append("| " + " | ".join("" if pd.isna(v) else str(v) for v in row) + " |")
    return "\n".join(lines)


def _groups_2010(mirror: Path) -> pd.Series:
    """Censo 2010's employed by SINCO group (its ``OCUACTIV_C``; 59 → 52), shares."""
    import pyarrow.parquet as pq
    frames = []
    for s in range(1, 33):
        f = mirror / f"cpv_personas_2010_{s:02d}.parquet"
        cols = {c.upper(): c for c in pq.read_schema(f).names}
        t = pq.read_table(f, columns=[cols["OCUACTIV_C"], cols["FACTOR"]]).to_pandas()
        t.columns = ["O", "W"]
        frames.append(t.dropna(subset=["O"]))
    d = pd.concat(frames, ignore_index=True)
    g = d["O"].str[:2].replace({"59": "52"})
    w = pd.to_numeric(d["W"])
    return w.groupby(g).sum() / w.sum()


def _shares(codes: pd.Series, table: pd.DataFrame) -> pd.Series:
    group = codes.index.map(dict(zip(table["CMO"], table["GROUP"].replace({"59": "52"}))))
    return codes.groupby(group).sum() / codes.sum()


def report(table: pd.DataFrame, pairs: pd.DataFrame, links: pd.DataFrame,
           codes: pd.Series, mirror: Path, path: Path) -> None:
    w = codes / codes.sum()
    t = table.set_index("CMO")
    in_table = codes.index.isin(pairs["CMO"])
    rules = (pd.DataFrame({"RULE": t.loc[codes.index, "RULE"], "W": w.to_numpy()})
             .groupby("RULE")["W"].agg(["size", "sum"])
             .rename(columns={"size": "codes", "sum": "share of 2000's employed"}))
    rules["share of 2000's employed"] = (rules["share of 2000's employed"] * 100).map(
        "{:.2f}%".format)
    split = pairs.assign(G=pairs["SINCO"].str[:2]).groupby("CMO")["G"].agg(
        lambda s: " ".join(sorted(set(s))))
    split = split[split.str.contains(" ")]
    rows = []
    for code in split.index:
        r = t.loc[code]
        rows.append((code, split[code], r["GROUP"], r["RULE"], r["SHARE"], r["PERSONS"],
                     f"{w.get(code, 0) * 100:.2f}%"))
    split_df = pd.DataFrame(rows, columns=["CMO", "table's groups", "GROUP", "RULE", "SHARE",
                                           "PERSONS", "2000"]).sort_values(
        "2000", key=lambda s: s.str.rstrip("%").astype(float), ascending=False)
    absent = [(c, t.loc[c, "GROUP"], t.loc[c, "RULE"], t.loc[c, "SHARE"], t.loc[c, "PERSONS"],
               f"{w[c] * 100:.3f}%") for c in codes.index[~in_table]]
    absent_df = pd.DataFrame(absent, columns=["CMO", "GROUP", "RULE", "SHARE", "PERSONS",
                                              "2000"])
    # the bridge on ENOE: 2012-T2 (CMO) bridged against 2012-T3 (SINCO), every employed
    a, b = _coe1(_BEFORE), _coe1(_AFTER)
    enoe = pd.DataFrame({
        "T2 bridged": _shares(a.groupby("p3")["fac"].sum(), table),
        "T3 SINCO": b.groupby(b["p3"].str[:2].replace({"59": "52"}))["fac"].sum()
        / b["fac"].sum()}).fillna(0) * 100
    enoe["diff"] = enoe["T2 bridged"] - enoe["T3 SINCO"]
    enoe.index.name = "GROUP"
    ok = links["SINCO"].str[:2].to_numpy() == links["CMO"].map(
        dict(zip(table["CMO"], table["GROUP"]))).to_numpy()
    census = pd.DataFrame({"2000 bridged": _shares(codes, table),
                           "2010": _groups_2010(mirror)}).fillna(0) * 100
    census["diff"] = census["2000 bridged"] - census["2010"]
    census.index.name = "GROUP"
    lines = [
        "# CMO → SINCO bridge for CGPV 2000 — build report",
        "",
        "Generated by `scripts/build_cmo_sinco.py --check` (do not edit). Source: INEGI's"
        " SINCO 2011 comparison tables (sheet `SINCO-CMO`, update of November 2012, from the"
        f" Internet Archive): {len(pairs):,} pairs, {pairs['SINCO'].nunique():,} SINCO unit"
        f" groups, {pairs['CMO'].nunique():,} CMO codes. CGPV 2000 uses {len(codes):,} codes;"
        f" {int(in_table.sum()):,} are in the table ({w[in_table].sum() * 100:.2f}% of its"
        " employed, weighted). ENOE's panel across INEGI's switch: "
        f"{len(links):,} persons employed in {_BEFORE} (CMO) and {_AFTER} (SINCO).",
        "",
        "## Rules",
        "",
        _md(rules, index=True),
        "",
        "## CMO codes the table splits across SINCO groups",
        "",
        "The panel's group: the SINCO group most of the code's linked persons take in"
        " 2012-T3 among the table's groups (`SHARE`, weighted; `PERSONS`, unweighted).",
        "",
        _md(split_df),
        "",
        "## CGPV 2000's codes the table lacks",
        "",
        f"The panel's group on {_MIN_PERSONS}+ linked persons, {_MIN_SHARE:.0%}+ of them"
        " agreeing; else the one group of the code's CMO subgroup; else not placed (99).",
        "",
        _md(absent_df),
        "",
        "## On ENOE",
        "",
        f"Every employed person of {_BEFORE} through the bridge against {_AFTER}'s SINCO"
        " groups (shares in points; 59 → 52). On the panel the linked persons' 2012-T3 group"
        f" is the bridge's for {ok.mean() * 100:.1f}% (unweighted; people change jobs, coders"
        " differ). Dissimilarity:"
        f" {enoe['diff'].abs().sum() / 2:.2f} points.",
        "",
        _md(enoe.round(2).sort_values("diff"), index=True),
        "",
        "## CGPV 2000 against Censo 2010",
        "",
        "Shares of the employed by SINCO group (points): ten years apart, not a check of the"
        f" bridge but of its plausibility. Dissimilarity: {census['diff'].abs().sum() / 2:.2f}"
        " points.",
        "",
        _md(census.round(2).sort_values("diff"), index=True),
        "",
    ]
    path.write_text("\n".join(lines), encoding="utf-8")


def main(argv: list[str] | None = None) -> int:
    parser = argparse.ArgumentParser(description=__doc__.split("\n\n")[0])
    parser.add_argument("--xls", type=Path, default=_DEFAULT_XLS, metavar="FILE")
    parser.add_argument("--download", action="store_true", help="refresh the workbook")
    parser.add_argument("--output", type=Path, default=_DEFAULT_OUTPUT, metavar="FILE")
    parser.add_argument("--mirror", type=Path, default=_DEFAULT_MIRROR, metavar="DIR")
    parser.add_argument("--check", action="store_true", help="also write --report")
    parser.add_argument("--report", type=Path, default=_DEFAULT_REPORT, metavar="FILE")
    args = parser.parse_args(argv)
    if args.download or not args.xls.exists():
        download(args.xls)
    pairs = table_pairs(args.xls)
    links = panel()
    codes = codes_2000(args.mirror)
    table = bridge(pairs, links, codes.index)
    write(table, args.output)
    print(f"{len(table):,} CMO codes → {args.output}")
    print(table["RULE"].value_counts().to_string())
    if args.check:
        report(table, pairs, links, codes, args.mirror, args.report)
        print(f"report → {args.report}")
    return 0


if __name__ == "__main__":
    raise SystemExit(main())
